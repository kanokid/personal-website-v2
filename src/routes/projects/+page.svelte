        <p>This was the project that i spent weeks working and waiting, and then when I built it and plugged it in, it blew a tantalum capacitor and blew burn holes into my rug.<br>
        The specs it was supposed to have was a ESP32 D1 mini running WLED, on a custom shield that had a LM2596-5.0 buck converter circuitry<br>(probably where I went wrong, because they are complex, and I had a ton of bugs in my design),<br>A fuse (put on the 5V line by accident, not the 12V line in), A level shifter for data stability,<br>and a spot to plug in a MAX9814 module with a gain jumper for audioreactive WLED,<br>and 2 terminal blocks for hookup (turns out I used the wrong footprint, so they didn't fit).</p>
